import assert from 'node:assert/strict';
import {selectDeliveryMethod,courierSelection,courierSlots,sellerAddress,sellerMapPage,courierPage} from '../delivery-modes.mjs';
import {calculateTotals} from '../pricing.mjs';

const state={cart:['shoe','hat'],quantities:{shoe:3,hat:1},products:{shoe:{price:3590,seller:'a'},hat:{price:1049,seller:'b'}},sellers:{a:{delivery:1},b:{delivery:100}},demoPricing:{productDiscount:3000,bonusDiscount:1000},deliverySelections:{},bundleSellers:['a']};
const initial=calculateTotals(state);
assert.equal(selectDeliveryMethod(state,'a','invalid'),false);
assert.equal(selectDeliveryMethod(state,'a','pickup'),false);
assert.equal(selectDeliveryMethod(state,'a','self'),true);
assert.equal(state.deliverySelections.a.address,sellerAddress);
assert.equal(calculateTotals(state).delivery,101);
assert.equal(selectDeliveryMethod(state,'a','courier'),true);
assert.equal(state.deliverySelections.a.delivery,354);
assert.equal(calculateTotals(state).delivery,454);
assert.equal(calculateTotals(state).bundleDiscount,initial.bundleDiscount);
state.deliverySelections.a=courierSelection('day3-all');
assert.equal(calculateTotals(state).delivery,149);
selectDeliveryMethod(state,'a','pickup');
assert.equal(state.deliverySelections.a,undefined);
state.deliverySelections.a={id:'post',address:'Кожевническая, 5',delivery:120};
selectDeliveryMethod(state,'a','courier');
assert.equal(state.deliverySelections.a.slotId,'day3-all');
assert.equal(state.deliverySelections.a.delivery,49);
selectDeliveryMethod(state,'b','self');
assert.equal(state.deliveryModes.a,'courier');
assert.equal(calculateTotals(state).delivery,50);
selectDeliveryMethod(state,'a','pickup');
assert.equal(state.deliverySelections.a.id,'post');
assert.equal(calculateTotals(state).delivery,121);
assert.equal(courierSelection('bad').slotId,'today-evening');
assert.equal(new Set(courierSlots.map(x=>x.id)).size,7);
const helpers={image:src=>`<img src="${src}">`,summary:'3 товара · 8 242,50 ₽',photo:'',money:n=>`${n} ₽`,slotId:'today-evening'};
assert.match(sellerMapPage(helpers),/Адрес продавца/);
assert.match(sellerMapPage(helpers),/Доставить сюда/);
const courier=courierPage(helpers);
assert.equal((courier.match(/type="radio"/g)||[]).length,7);
assert.equal((courier.match(/ checked/g)||[]).length,1);
assert.match(courier,/Продолжить/);
console.log('24 delivery mode assertions passed');
